    void update(float dt, const InputFrame& input) {
        PFParams::apply(input, 0, &bar1, BAR_MIN, BAR_MAX, BAR_STEP);
        PFParams::apply(input, 1, &bar2, BAR_MIN, BAR_MAX, BAR_STEP);
        PFParams::apply(input, 2, &bar3, BAR_MIN, BAR_MAX, BAR_STEP);
        PFParams::apply(input, 3, &bar4, BAR_MIN, BAR_MAX, BAR_STEP);
    }

    void draw() {
        PFCanvas::setFrame(FRAME_W, FRAME_H);

        constexpr int COL_WIDTH = FRAME_W / 4;
        constexpr float BAR_WIDTH = (float)COL_WIDTH * 0.75f;
        constexpr float MARGIN = ((float)COL_WIDTH - BAR_WIDTH) * 0.5f;

        const float kv[4] = {bar1, bar2, bar3, bar4};
        float barHeights[4];
        int barHeightsPxFloor[4];

        for (int i = 0; i < 4; ++i) {
            barHeights[i] = (kv[i] / 100.0f) * (float)FRAME_H;
            barHeightsPxFloor[i] = (int)barHeights[i];
        }

        const int leftEdgeX = (int)MARGIN;
        const int rightEdgeX = (int)(MARGIN + BAR_WIDTH - 1.0f);

        for (int y = 0; y < FRAME_H; ++y) {
            const int currentY = FRAME_H - 1 - y;

            for (int x = 0; x < FRAME_W; ++x) {
                const int colIndex = (x / COL_WIDTH > 3) ? 3 : (x / COL_WIDTH);
                const int colX = x % COL_WIDTH;

                const float barHeightPx = barHeights[colIndex];
                const int barHeightFloor = barHeightsPxFloor[colIndex];
                float val = 0.0f;

                if ((float)colX >= MARGIN && (float)colX < (MARGIN + BAR_WIDTH) && (float)currentY < barHeightPx) {
                    const bool isLeftEdge = (colX == leftEdgeX);
                    const bool isRightEdge = (colX == rightEdgeX);
                    const bool isTopEdge = (currentY >= barHeightFloor - 1);
                    const bool isBottomEdge = (currentY == 0);

                    if (isLeftEdge || isRightEdge || isTopEdge || isBottomEdge) {
                        val = 1.0f;
                    } else {
                        val = 0.25f;
                    }
                }

                if (val < 0.0f) val = 0.0f;
                else if (val > 1.0f) val = 1.0f;

                const int li = (int)(val * 255.0f + 0.5f);
                PFCanvas::setPixel(x, y, RAMP_LUT[li][0], RAMP_LUT[li][1], RAMP_LUT[li][2]);
            }
        }

        PFCanvas::present();
    }

